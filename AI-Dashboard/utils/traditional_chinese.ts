const terms = new RegExp(`${Object.keys(phrases).join("|")}|[${Object.keys(characters).join("")}]`, "g")

function convert(text: string): string {
  return text.replace(terms, (term) => phrases[term] ?? characters[term])
}

export function translateTraditionalChinese(text: string): string {
  // Keep custom account names intact in deletion and Keychain messages.
  const accountMessage = text.match(/^(确认删除「|账号「)([\s\S]*)(」[\s\S]*)$/)
  if (accountMessage) {
    const [, prefix, name, suffix] = accountMessage
    return `${convert(prefix)}${name}${convert(suffix)}`
  }
  return convert(text)
}
