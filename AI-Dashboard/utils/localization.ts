export function localize(text: string | null | undefined): string | null | undefined {
  if (!text) return text
  if (getDashboardLanguage() === "en") return translateEnglish(text)
  const translated = CHINESE[text]
  return typeof translated === "string" ? translated : text
}

function translateEnglish(text: string): string {
  if (!/\p{Script=Han}/u.test(text)) return text
  const trimmed = text.trim()
  const normalized = trimmed.replace(/\s+/g, " ")
  const exact = ENGLISH[normalized]
  if (typeof exact === "string") return exact
  for (const [pattern, replacement] of templates) {
    const match = trimmed.match(pattern)
    if (match) {
      return replacement.replace(/\$(\d+)/g, (_, index: string) => {
        const value = match[Number(index)] ?? ""
        // The account names in delete and Keychain messages come from user input.
        if (Number(index) === 1 && /^(确认删除|账号「)/.test(normalized)) return value
        return translateEnglish(value)
      })
    }
  }
  return text
}
