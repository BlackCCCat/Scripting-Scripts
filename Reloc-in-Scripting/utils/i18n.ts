import { STORAGE_KEYS } from "../constants";
import type { AppLanguage, AppSettings } from "../types";

export type ResolvedLanguage = "zh-Hans" | "en";

export function resolveLanguageCode(language: AppLanguage = "system"): ResolvedLanguage {
  if (language === "en") return "en";
  if (language === "zh-Hans") return "zh-Hans";
  const sys =
    typeof Device !== "undefined"
      ? (Device.systemLanguageCode || Device.systemLocale || "")
      : "";
  return sys.toLowerCase().startsWith("en") ? "en" : "zh-Hans";
}

export function isChineseLanguage(language: AppLanguage = "system"): boolean {
  return resolveLanguageCode(language) === "zh-Hans";
}

export function loadActiveLanguage(): AppLanguage {
  try {
    if (typeof Storage === "undefined") return "system";
    const saved = Storage.get<Partial<AppSettings>>(STORAGE_KEYS.settings);
    const raw = saved?.language;
    if (raw === "en" || raw === "zh-Hans" || raw === "system") return raw;
  } catch {
    // 忽略读取失败，默认跟随系统
  }
  return "system";
}

export function formatText(template: string, ...args: Array<string | number>): string {
  let out = template;
  for (let i = 0; i < args.length; i += 1) {
    out = out.replaceAll(`{${i}}`, String(args[i]));
  }
  return out;
}

